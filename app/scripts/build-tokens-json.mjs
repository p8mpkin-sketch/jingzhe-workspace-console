#!/usr/bin/env node
// Dev-only: regenerate design/tokens.json from design/tokens.css, so the JSON mirror cannot drift from the source.
// Usage: node scripts/build-tokens-json.mjs [--check]   (--check exits 1 when the file on disk is out of date)
import fs from 'node:fs';
const cssUrl = new URL('../../design/tokens.css', import.meta.url);
const outUrl = new URL('../../design/tokens.json', import.meta.url);
const css = fs.readFileSync(cssUrl, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const block = (re) => Object.fromEntries([...(css.match(re)?.[1] ?? '').matchAll(/--jz-([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const light = block(/:root\s*\{([\s\S]*?)\n\}/); const darkOnly = block(/html\.dark\s*\{([\s\S]*?)\n\}/);
const hex = (v) => { const m = v.match(/^(\d+) (\d+) (\d+)$/); return m ? '#' + m.slice(1).map((n) => Number(n).toString(16).padStart(2, '0')).join('').toUpperCase() : v; };
const isColor = (v) => /^\d+ \d+ \d+$/.test(v);
const pick = (src, prefix) => Object.fromEntries(Object.entries(src).filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));
const colors = (src) => Object.fromEntries(Object.entries(src).filter(([, v]) => isColor(v)).map(([k, v]) => [k, hex(v)]));
const type = {};
for (const [k, v] of Object.entries(light)) { if (k.startsWith('text-')) (type[k.slice(5)] ||= {}).size = v; if (k.startsWith('leading-')) (type[k.slice(8)] ||= {}).line = v; }
const json = {
  meta: { name: 'Jingzhe Workspace', version: '3.0.0', direction: 'A+ Living Instrument Panel', mode: ['light', 'dark'], source: 'design/tokens.css (generated by app/scripts/build-tokens-json.mjs; do not edit by hand)' },
  color: { light: colors(light), dark: { ...colors(light), ...colors(darkOnly) } },
  semantic: Object.fromEntries(Object.entries(light).filter(([k, v]) => /^(sev|trace|line|approval|state|focus)/.test(k) && !/^\d+px$/.test(v) || /^(sev|trace|approval)-/.test(k)).map(([k, v]) => [k, v])),
  font: pick(light, 'font-'),
  type,
  weight: pick(light, 'weight-'),
  radius: pick(light, 'radius-'),
  spacing: pick(light, 'space-'),
  layout: Object.fromEntries(Object.entries(light).filter(([k]) => /^(sidebar|topbar|content|page|prose|dialog|control|touch|table|row|inspector|icon|line-w|line-cap)/.test(k))),
  shadow: { light: pick(light, 'shadow-'), dark: { ...pick(light, 'shadow-'), ...pick(darkOnly, 'shadow-') } },
  motion: { ...pick(light, 'motion-'), ease: light.ease, 'ease-exit': light['ease-exit'], rise: light.rise },
};
const text = JSON.stringify(json, null, 2) + '\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outUrl) ? fs.readFileSync(outUrl, 'utf8') : '';
  if (cur !== text) { console.error('design/tokens.json is out of date: run node scripts/build-tokens-json.mjs'); process.exit(1); }
  console.log('design/tokens.json matches design/tokens.css');
} else { fs.writeFileSync(outUrl, text); console.log('wrote design/tokens.json'); }
